CREATE OR REPLACE FUNCTION public.stylora_workflow_retryable_code(p_code text) RETURNS boolean
LANGUAGE sql IMMUTABLE STRICT SECURITY INVOKER SET search_path = '' AS $$
  WITH normalized AS (
    SELECT upper(p_code) AS code
  ), legacy AS (
    SELECT CASE code
      WHEN 'OPERATION_PERSISTENCE_FAILED' THEN 'WORKFLOW_COMMIT_UNAVAILABLE'
      WHEN 'OPERATION_CHECKPOINT_UNAVAILABLE' THEN 'CHECKPOINT_UNAVAILABLE'
      ELSE code END AS code
    FROM normalized
  )
  SELECT code IN ('PROVIDER_TIMEOUT', 'PROVIDER_NETWORK_ERROR', 'PROVIDER_RATE_LIMITED', 'PROVIDER_SERVER_ERROR',
    'OPENAI_CONNECTION_FAILED', 'PROVIDER_CAPACITY_BUSY', 'PROVIDER_DAILY_BUDGET_EXHAUSTED',
    'WORKFLOW_CHECKPOINT_UNAVAILABLE', 'WORKFLOW_COMMIT_UNAVAILABLE', 'CHECKPOINT_UNAVAILABLE', 'CHECKPOINT_COMMIT_PENDING')
    OR code ~ '^OPENAI_HTTP_(429|500|502|503|504)$' FROM legacy;
$$;
REVOKE ALL ON FUNCTION public.stylora_workflow_retryable_code(text) FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.stylora_workflow_retryable_code(text) TO service_role;
